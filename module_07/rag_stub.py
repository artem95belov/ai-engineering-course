NO_DATA_ANSWER = "В базе знаний ответа на этот вопрос нет."

# запись засчитывается, только если в вопросе нашлось хотя бы два её ключа —
# одно случайное совпадение («насос» в вопросе про отпускной график насосной
# станции) источником не считаем
_MIN_HITS = 2


def _words(text: str) -> list:
    """Слова вопроса в нижнем регистре, без пунктуации (дефис сохраняем)."""
    return re.findall(r"[\w-]+", text.lower())


def _score(question_words: list, keys: list) -> int:
    """Сколько ключей записи встретилось в вопросе (по началу слова)."""
    hits = 0
    for key in keys:
        if any(w.startswith(key) for w in question_words):
            hits += 1
    return hits


def answer(question: str) -> dict:
    """Отвечает на вопрос по базе знаний ПромТеха.

    Контракт совпадает с настоящим RAG Модуля 4 (подключается через
    rag_adapter.py): возвращает {"answer": str, "sources": list[str]};
    если ответа в базе нет — sources пустой.
    """
    words = _words(question)

    best, best_hits = None, 0
    for record in _KB:
        hits = _score(words, record["keys"])
        if hits > best_hits:
            best, best_hits = record, hits

    if best is None or best_hits < _MIN_HITS:
        return {"answer": NO_DATA_ANSWER, "sources": []}

    return {"answer": best["answer"], "sources": list(best["sources"])}


